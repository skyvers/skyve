package modules.admin.ControlPanel.actions;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.UUID;

import javax.tools.JavaFileObject;

import org.apache.commons.text.StringEscapeUtils;
import org.skyve.content.MimeType;
import org.skyve.domain.messages.DomainException;
import org.skyve.domain.messages.Message;
import org.skyve.domain.messages.ValidationException;
import org.skyve.impl.util.XMLMetaData;
import org.skyve.metadata.controller.Download;
import org.skyve.metadata.controller.DownloadAction;
import org.skyve.util.FileUtil;
import org.skyve.util.RuntimeCompiler;
import org.skyve.web.UserAgentType;
import org.skyve.web.WebContext;

import jakarta.annotation.Nonnull;
import modules.admin.ControlPanel.ControlPanelExtension;
import modules.admin.domain.ControlPanel;
import modules.admin.domain.ControlPanel.SailExecutor;

/**
 * Downloads the Control Panel's SAIL as a JUnit 5 test, {@code sail.jar}, generated by the PrimeFaces Inline Web Driver
 * executor and compiled on the server against the jars in {@code <content>/compile/} (see
 * {@link #COMPILE_FOLDER_CONTENTS}). The jar holds the class {@code Sail} and its source, {@code Sail.java}. When the
 * test cannot be compiled, the download is {@code sail.txt} instead: why, what the folder needs, then the source.
 */
public class DownloadSAIL extends DownloadAction<ControlPanelExtension> {
	/** The generated class's name, in the default package. */
	static final String CLASS_NAME = "Sail";

	/**
	 * What {@code <content>/compile/} must hold, as told to a user whose download did not compile. The test extends
	 * the harness's {@code util.sail.PrimeFacesSelenium} and uses JUnit 5's annotations and {@code UserAgentType}.
	 */
	static final String COMPILE_FOLDER_CONTENTS = """
			The Control Panel compiles the generated test against every .jar file in its compile folder,
			<content>/compile/. It needs:
			- test.jar: the SAIL harness, the util/sail classes of a Skyve project's tests, made with
			  jar cf test.jar -C target/test-classes util/sail
			- junit-jupiter-api (JUnit 5's annotations) and skyve-core (UserAgentType); with apiguardian-api too, the
			  compiler does not warn about JUnit's annotations.
			Or copy all the project's test dependencies there as well as test.jar:
			  mvn dependency:copy-dependencies -DincludeScope=test -DoutputDirectory=<content>/compile
			""";

	/**
	 * Generates the Java test methods from the Control Panel's SAIL with the PrimeFaces Inline Web Driver executor, for
	 * {@link #download(ControlPanelExtension, WebContext)} to compile.
	 *
	 * <p>Side effects: puts the generated methods in the Control Panel's results.
	 *
	 * @param bean the Control Panel
	 * @param webContext the web context
	 * @throws ValidationException if another executor is chosen (only this one makes Java), a value the execution needs
	 * 								is not entered, or the SAIL user cannot be found
	 * @throws Exception if the SAIL cannot be executed
	 */
	@Override
	public void prepare(ControlPanelExtension bean, WebContext webContext)
	throws Exception {
		SailExecutor executor = bean.getSailExecutor();
		if ((executor != null) && (executor != SailExecutor.primeFacesInlineWebDriver)) {
			throw new ValidationException(new Message(ControlPanel.sailExecutorPropertyName,
														"Download makes a Java test, which only the " +
															SailExecutor.primeFacesInlineWebDriver.toLocalisedDescription() +
															" executor generates. Generate Test shows this executor's output."));
		}
		bean.setResults(ExecuteSAIL.generate(bean));
	}

	/**
	 * Compiles the test that {@link #prepare(ControlPanelExtension, WebContext)} generated against the jars in
	 * {@code <content>/compile/}; see {@link #compile(String, File)}.
	 *
	 * <p>Side effects: clears the Control Panel's results.
	 *
	 * @param bean the Control Panel
	 * @param webContext the web context
	 * @return {@code sail.jar}, or {@code sail.txt} with why the test did not compile and its source
	 * @throws IOException if the compiled class's folder cannot be created or deleted
	 */
	@Override
	public Download download(ControlPanelExtension bean, WebContext webContext)
	throws IOException {
		UserAgentType userAgentType = XMLMetaData.unmarshalSAILString(bean.getSail()).getUserAgentType();
		String source = sailSource(bean.getUnescapedResults(), bean.getSailBaseUrl(), userAgentType);
		bean.setResults(null);
		return compile(source, new File(RuntimeCompiler.COMPILE_PATH));
	}

	/**
	 * Compiles the generated test against every jar in a compile folder.
	 *
	 * <p>Side effects: writes the class and its source to a new folder in the compile folder, and deletes it again.
	 *
	 * @param source the test's source, from {@link #sailSource(String, String, UserAgentType)}
	 * @param compileFolder the folder with the jars to compile against
	 * @return {@code sail.jar} with {@code Sail.class} and {@code Sail.java}; or {@code sail.txt} with why the test did
	 * 			not compile (no jars, or the compiler's error with the jars it had), {@link #COMPILE_FOLDER_CONTENTS} and
	 * 			the source
	 * @throws IOException if the class's folder cannot be created or deleted
	 */
	static @Nonnull Download compile(@Nonnull String source, @Nonnull File compileFolder) throws IOException {
		List<String> classPath = classPath(compileFolder);
		if (classPath.isEmpty()) {
			return notCompiled("The test was not compiled: there are no .jar files in " + compileFolder.getAbsolutePath(),
								source);
		}

		JavaFileObject java = Objects.requireNonNull(RuntimeCompiler.javaSource(CLASS_NAME, source));
		File outputFolder = new File(compileFolder, UUID.randomUUID().toString());
		Files.createDirectories(outputFolder.toPath());
		try {
			if (! RuntimeCompiler.compile(java, outputFolder.getAbsolutePath(), classPath.toArray(new String[0]))) {
				throw new DomainException("The compiler returned false");
			}
			Files.writeString(new File(outputFolder, CLASS_NAME + ".java").toPath(), source, StandardCharsets.UTF_8);
			ByteArrayOutputStream out = new ByteArrayOutputStream(4096);
			FileUtil.createJarArchive(outputFolder, out);
			return new Download("sail.jar", out.toByteArray(), MimeType.zip);
		}
		catch (Exception e) {
			List<String> jarNames = new ArrayList<>(classPath.size());
			for (String jar : classPath) {
				jarNames.add(new File(jar).getName());
			}
			return notCompiled("The test did not compile against the jars in " + compileFolder.getAbsolutePath() +
									" (" + String.join(", ", jarNames) + "):\n" + e.getMessage(),
								source);
		}
		finally {
			FileUtil.delete(outputFolder);
		}
	}

	/**
	 * Returns the jars in a compile folder, in name order.
	 *
	 * @param compileFolder the folder
	 * @return the jars' paths; empty if there are none or the folder does not exist
	 */
	static @Nonnull List<String> classPath(@Nonnull File compileFolder) {
		File[] jars = compileFolder.listFiles(file -> file.isFile() && file.getName().endsWith(".jar"));
		List<String> result = new ArrayList<>();
		if (jars != null) {
			Arrays.sort(jars);
			for (File jar : jars) {
				result.add(jar.getAbsolutePath());
			}
		}
		return result;
	}

	/**
	 * Returns {@code sail.txt}: why the test did not compile, what the compile folder needs, then the source.
	 */
	private static @Nonnull Download notCompiled(@Nonnull String why, @Nonnull String source) {
		return new Download("sail.txt", why + "\n\n" + COMPILE_FOLDER_CONTENTS + "\n" + source, MimeType.plain);
	}

	/**
	 * Returns the source of the JUnit 5 test class {@code Sail} (default package, tagged {@code sail}) around the
	 * generated test methods. It extends the SAIL harness's {@code util.sail.PrimeFacesSelenium} and starts the browser
	 * that {@code util.sail.SailWorkflow.defaultBrowser} gives the automation's user agent type, with the base URL as the
	 * browser configuration's own value: so {@code -Dsail.baseUrl}, {@code SAIL_BASE_URL} and the properties file
	 * override it, and the other SAIL settings ({@code sail.browser}, {@code sail.headless},
	 * {@code sail.timeoutSeconds}) apply. Selenium Manager finds the browser's driver.
	 *
	 * @param methods the generated test methods, ending with the {@code @Test} method that calls the others
	 * @param baseUrl the server's base URL, ending in {@code /}
	 * @param userAgentType the automation's user agent type
	 * @return the source
	 */
	static @Nonnull String sailSource(@Nonnull String methods, @Nonnull String baseUrl, @Nonnull UserAgentType userAgentType) {
		StringBuilder result = new StringBuilder(methods.length() + 1536);
		result.append("import org.junit.jupiter.api.AfterEach;\n");
		result.append("import org.junit.jupiter.api.BeforeEach;\n");
		result.append("import org.junit.jupiter.api.Tag;\n");
		result.append("import org.junit.jupiter.api.Test;\n");
		result.append("import org.skyve.web.UserAgentType;\n\n");
		result.append("import util.sail.PrimeFacesSelenium;\n");
		result.append("import util.sail.SailWorkflow;\n\n");
		result.append("/**\n");
		result.append(" * Generated by the Skyve Control Panel from a SAIL automation. The base URL is a default:\n");
		result.append(" * -Dsail.baseUrl, SAIL_BASE_URL or sail.baseUrl in ~/.skyve/sail.properties overrides it,\n");
		result.append(" * and the other SAIL settings (sail.browser, sail.headless, sail.timeoutSeconds) apply.\n");
		result.append(" */\n");
		result.append("@Tag(\"sail\")\n");
		result.append("public class ").append(CLASS_NAME).append(" extends PrimeFacesSelenium {\n");
		result.append("\t@BeforeEach\n");
		result.append("\tvoid setup() {\n");
		result.append("\t\tstartBrowser(SailWorkflow.defaultBrowser(UserAgentType.").append(userAgentType.name()).append(')');
		result.append(".baseUrl(\"").append(StringEscapeUtils.escapeJava(baseUrl)).append("\"));\n");
		result.append("\t}\n\n");
		result.append("\t@AfterEach\n");
		result.append("\tvoid teardown() {\n");
		result.append("\t\tstopBrowser();\n");
		result.append("\t}\n\n");
		result.append(methods);
		result.append("}\n");
		return result.toString();
	}
}
